// WHY THIS FILE EXISTS
// The drill pages quote real published figures -- 200-250 ms simple visual
// reaction, 20-40 ms saccade durations, 16.7 ms frame quantization at 60 Hz.
// Until now those appeared as bare parenthetical name-drops with no way for a
// reader or an answer engine to check them. A named citation nobody can follow
// is worth very little as a trust signal, and an unverifiable one is worse than
// none: it is exactly the failure mode AI systems now cross-check for.
//
// RULES FOR ADDING AN ENTRY
//   1. The work must exist and must actually say what the page claims.
//   2. Prefer a DOI over a publisher landing page -- DOIs do not rot.
//   3. `url` is optional. An entry with no stable identifier (an out-of-print
//      report, a dead university URL) keeps the citation and omits the link
//      rather than inventing one that resolves somewhere else.
//   4. Never add a source to pad the list. Each one is referenced by name in
//      the body copy of at least one page that includes it.
//
// This site publishes no data of its own -- scores never leave localStorage --
// so every number on a drill page traces to one of these.

